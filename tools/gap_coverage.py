"""Write kb/gaps/COVERAGE.md: for each gap, its status, India evidence, global examples by tier,
and the scenarios whose expectations trigger it. Run: python tools/gap_coverage.py"""
from pathlib import Path
import sys

import yaml

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from orca import kb as kbmod  # noqa: E402


def scenario_hits() -> dict[str, list[str]]:
    hits: dict[str, list[str]] = {}
    for f in sorted((ROOT / "scenarios").glob("*.yaml")):
        sc = yaml.safe_load(f.read_text()) or {}
        for e in sc.get("events") or []:
            for x in e.get("expect") or []:
                if x.get("gap"):
                    hits.setdefault(x["gap"], [])
                    if sc["id"] not in hits[x["gap"]]:
                        hits[x["gap"]].append(sc["id"])
    return hits


def main() -> None:
    k = kbmod.load()
    hits = scenario_hits()
    rows = ["# Gap coverage (generated by tools/gap_coverage.py; do not edit)", "",
            "Tiers: **V** = human-verified record, **A** = quote auto-checked against the PDF (not human-verified).",
            "All network links in the scenarios are emulated.", "",
            "| Gap | Status | India evidence (verified / total) | Global examples | Relation | Scenarios |",
            "|---|---|---|---|---|---|"]
    for gid, g in k.gaps.items():
        ev = g.get("evidence", [])
        nv = sum(1 for e in ev if k.records.get(e, {}).get("verified"))
        gx = g.get("global_examples") or []
        gl = ", ".join(f"{e['jurisdiction']} {e['clause']} ({'V' if e['tier'] == 'verified' else 'A'})" for e in gx) or "-"
        rel = ", ".join(sorted({e["relation"] for e in gx})) or "-"
        rows.append(f"| {gid} | {g['status']} | {nv} / {len(ev)} | {gl} | {rel} | {', '.join(hits.get(gid, [])) or '-'} |")
    conf = [g for g in k.gaps.values() if g["status"] == "confirmed"]
    allx = [e for g in conf for e in g.get("global_examples") or []]
    rows += ["", f"Confirmed gaps: {len(conf)}. Global examples: {len(allx)} "
             f"({sum(e['tier'] == 'verified' for e in allx)} verified, {sum(e['tier'] == 'auto_checked' for e in allx)} auto-checked), "
             f"from {len({e['jurisdiction'] for e in allx})} jurisdictions.",
             f"Gaps exercised by at least one scenario: {sum(1 for g in conf if hits.get(g['id']))} of {len(conf)}."]
    (ROOT / "kb/gaps/COVERAGE.md").write_text("\n".join(rows) + "\n")
    print("\n".join(rows))


if __name__ == "__main__":
    main()
